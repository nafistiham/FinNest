"""Turn real Bangladesh district boundaries into compact SVG paths for the console.

The campaign map drew Bangladesh as a hand-made twenty-four point outline with eight circles on
it, and said so in its own caption. This replaces the outline with the real thing.

Source: geoBoundaries gbOpen, BGD ADM2 (64 districts), CC BY 4.0.
  https://www.geoboundaries.org  ·  https://github.com/wmgeolab/geoBoundaries
The licence requires attribution, which the map carries on screen.

Run:  python3 tools/build_bd_districts.py <geojson> > web/src/lib/bdDistricts.ts

Emitted in degrees, not pixels. Two maps draw this country - the campaign map fits it to its own
box, the cash-out map shares a projection with the tills plotted on top of it - so the one thing
they can share is the shape itself, and each projects it with the function it already has.

What it does, and why each step is needed to ship this in a browser:

* keeps the largest ring of each district - the rest are offshore islands and river chars that
  vanish at this size anyway, and carrying them triples the file;
* simplifies with Douglas-Peucker in degrees, at a tolerance chosen so the shapes stay
  recognisable at 420x340 but stop carrying metres of coastline detail nobody can see;
* projects once, here, rather than in the browser on every render;
* rounds to one decimal in viewBox units, which is a tenth of a pixel.

1.6 MB of GeoJSON becomes about 40 KB of path data.
"""

from __future__ import annotations

import json
import sys

# About 330 m. Chosen against the closest zoom these shapes are drawn at, not the country view:
# the cash-out zoom is an 18 km box in a 420 px square, where 330 m is eight pixels and the coast
# still reads as coast. 600 m halves the file and looks chewed at that zoom; 170 m doubles it to
# move a line four pixels.
TOLERANCE = 0.003
PRECISION = 3              # degrees; about 110 m, finer than the simplification above


def rings(geometry: dict) -> list[list[tuple[float, float]]]:
    kind, coords = geometry["type"], geometry["coordinates"]
    if kind == "Polygon":
        return [[(x, y) for x, y in coords[0]]]
    if kind == "MultiPolygon":
        return [[(x, y) for x, y in poly[0]] for poly in coords]
    raise ValueError(f"unexpected geometry {kind}")


def simplify(points: list[tuple[float, float]], tol: float) -> list[tuple[float, float]]:
    """Douglas-Peucker. Keeps the shape, drops the coastline detail nobody can see at 420px."""
    if len(points) < 3:
        return points
    first, last = points[0], points[-1]
    dx, dy = last[0] - first[0], last[1] - first[1]
    norm = (dx * dx + dy * dy) ** 0.5
    worst, index = 0.0, 0
    for i in range(1, len(points) - 1):
        px, py = points[i]
        if norm == 0:
            d = ((px - first[0]) ** 2 + (py - first[1]) ** 2) ** 0.5
        else:
            d = abs(dy * px - dx * py + last[0] * first[1] - last[1] * first[0]) / norm
        if d > worst:
            worst, index = d, i
    if worst <= tol:
        return [first, last]
    left = simplify(points[: index + 1], tol)
    right = simplify(points[index:], tol)
    return left[:-1] + right


def main(path: str) -> None:
    data = json.load(open(path))
    features = data["features"]

    out: list[tuple[str, list[tuple[float, float]]]] = []
    for feature in sorted(features, key=lambda f: f["properties"]["shapeName"]):
        name = feature["properties"]["shapeName"]
        biggest = max(rings(feature["geometry"]), key=len)
        pts = [(round(lon, PRECISION), round(lat, PRECISION)) for lon, lat in simplify(biggest, TOLERANCE)]
        out.append((name, pts))

    points = sum(len(p) for _, p in out)
    print("/**")
    print(" * Bangladesh districts as rings of [longitude, latitude].")
    print(" *")
    print(" * Generated by tools/build_bd_districts.py from geoBoundaries gbOpen BGD ADM2,")
    print(" * CC BY 4.0 - https://www.geoboundaries.org. Do not edit by hand; re-run the script.")
    print(" *")
    print(f" * {len(out)} districts, {points} points, largest ring each, simplified at {TOLERANCE} degrees.")
    print(" * Degrees rather than pixels, because the two maps that draw this country project it")
    print(" * differently: one fits it to its box, the other shares a projection with the tills on top.")
    print(" */")
    print()
    print("export type Ring = [number, number][]")
    print()
    print("export const BD_DISTRICTS: Record<string, Ring> = {")
    for name, pts in out:
        flat = ",".join(f"[{lon},{lat}]" for lon, lat in pts)
        print(f"  {json.dumps(name)}: [{flat}],")
    print("}")
    print()
    print("/** The bounds of the whole country, for a map that wants to fit it to a box. */")
    lons = [lon for _, pts in out for lon, _ in pts]
    lats = [lat for _, pts in out for _, lat in pts]
    print(f"export const BD_BOUNDS = {{ west: {min(lons)}, east: {max(lons)}, "
          f"south: {min(lats)}, north: {max(lats)} }}")
    print()
    print("/** Build an SVG path from a ring, with whatever projection the caller draws in. */")
    print("export function ringPath(ring: Ring, project: (lon: number, lat: number) => [number, number]): string {")
    print("  let d = ''")
    print("  for (let i = 0; i < ring.length; i += 1) {")
    print("    const [px, py] = project(ring[i]![0], ring[i]![1])")
    print("    d += `${i ? 'L' : 'M'}${px.toFixed(1)} ${py.toFixed(1)}`")
    print("  }")
    print("  return `${d}Z`")
    print("}")
    print()
    print("/** The attribution the licence requires, shown on every map that draws these. */")
    print("export const BD_DISTRICTS_SOURCE = 'Boundaries: geoBoundaries gbOpen BGD ADM2, CC BY 4.0'")


if __name__ == "__main__":
    main(sys.argv[1])
