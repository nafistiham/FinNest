#!/usr/bin/env python3
"""Generate the FinNest brand assets from the logo (idempotent).

Run from apps/mobile (needs Pillow; it is not installed by this script):

  python3 tool/make_brand_assets.py                 # rebuild from assets/brand/finnest_logo.png
  python3 tool/make_brand_assets.py path/to/logo.jpeg

Source (optional): the full app-icon render (mark + "FinNest" wordmark on an
off-white rounded card). The source image is not part of the repository.
Without a source, the Android icons are rebuilt from the committed
`assets/brand/finnest_logo.png`.

Writes:
  assets/brand/finnest_logo.png                  the mark only, transparent, 512 px
  android/.../mipmap-*/ic_launcher.png           legacy icon 48/72/96/144/192 px
  android/.../mipmap-*/ic_launcher_foreground.png adaptive foreground, 108 dp
  android/.../mipmap-anydpi-v26/ic_launcher.xml  adaptive icon
  android/.../values/colors.xml                  ic_launcher_background, launch_background
  android/.../drawable-*/launch_logo.png         splash mark, 96 dp

The adaptive foreground puts the mark at 56 dp on the 108 dp canvas: the
shield's top corners then stay inside the 66 dp safe-zone circle, so a round
launcher mask never clips them.
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"
MARK = ROOT / "assets/brand/finnest_logo.png"

# Off-white of the logo's card (sampled), used behind every icon and the splash.
OFF_WHITE = (0xF6, 0xF8, 0xEA)
OFF_WHITE_HEX = "#FFF6F8EA"

DENSITIES = {"mdpi": 1.0, "hdpi": 1.5, "xhdpi": 2.0, "xxhdpi": 3.0, "xxxhdpi": 4.0}


def extract_mark(src: Path) -> Image.Image:
    """The mark above the wordmark, with the off-white keyed out to alpha."""
    im = Image.open(src).convert("RGB")
    w, h = im.size
    # Mark region: above the wordmark (which starts at ~66% of the height).
    region = (int(w * 0.15), int(h * 0.12), int(w * 0.85), int(h * 0.66))
    crop = im.crop(region)
    px = crop.load()
    cw, ch = crop.size
    minx, miny, maxx, maxy = cw, ch, 0, 0
    for y in range(ch):
        for x in range(cw):
            r, g, b = px[x, y]
            if min(r, g, b) < 200 or max(r, g, b) - min(r, g, b) > 60:
                minx, maxx = min(minx, x), max(maxx, x)
                miny, maxy = min(miny, y), max(maxy, y)
    side = max(maxx - minx, maxy - miny)
    pad = int(side * 0.04)
    cx, cy = (minx + maxx) // 2, (miny + maxy) // 2
    half = side // 2 + pad
    box = (cx - half, cy - half, cx + half, cy + half)
    sq = crop.crop(box).convert("RGBA")
    sp = sq.load()
    for y in range(sq.size[1]):
        for x in range(sq.size[0]):
            r, g, b, _ = sp[x, y]
            # Distance from the card's off-white (the card is a light gradient).
            d = max(abs(r - 250), abs(g - 251), abs(b - 242))
            a = 0 if d <= 14 else 255 if d >= 46 else int((d - 14) * 255 / 32)
            sp[x, y] = (r, g, b, a)
    return sq.resize((512, 512), Image.LANCZOS)


def on_canvas(mark: Image.Image, canvas: int, mark_px: int, bg) -> Image.Image:
    out = Image.new("RGBA", (canvas, canvas), bg)
    m = mark.resize((mark_px, mark_px), Image.LANCZOS)
    off = (canvas - mark_px) // 2
    out.alpha_composite(m, (off, off))
    return out


def write(path: Path, img: Image.Image) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, optimize=True)
    print(f"wrote {path.relative_to(ROOT)} ({img.size[0]} px)")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")


def main(argv: list[str]) -> int:
    src = Path(argv[0]) if argv else None
    if src is not None and src.exists():
        write(MARK, extract_mark(src))
    elif not MARK.exists():
        print(f"no logo at {src} and no {MARK.relative_to(ROOT)}; default icons kept")
        return 1
    mark = Image.open(MARK).convert("RGBA")

    for name, k in DENSITIES.items():
        legacy = round(48 * k)
        # Legacy icon: the mark at ~80% on the off-white square.
        write(
            RES / f"mipmap-{name}/ic_launcher.png",
            on_canvas(mark, legacy, round(legacy * 0.8), OFF_WHITE + (255,)),
        )
        write(
            RES / f"mipmap-{name}/ic_launcher_foreground.png",
            on_canvas(mark, round(108 * k), round(56 * k), (0, 0, 0, 0)),
        )
        write(
            RES / f"drawable-{name}/launch_logo.png",
            mark.resize((round(96 * k), round(96 * k)), Image.LANCZOS),
        )

    write_text(
        RES / "mipmap-anydpi-v26/ic_launcher.xml",
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/make_brand_assets.py: the FinNest mark on the logo off-white. -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
        "</adaptive-icon>\n",
    )
    write_text(
        RES / "values/colors.xml",
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tool/make_brand_assets.py: the off-white of the FinNest logo card. -->\n"
        "<resources>\n"
        f'    <color name="ic_launcher_background">{OFF_WHITE_HEX}</color>\n'
        f'    <color name="launch_background">{OFF_WHITE_HEX}</color>\n'
        "</resources>\n",
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
